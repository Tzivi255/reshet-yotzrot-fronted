// סינון הגלריה לפי אזורים וקטגוריות מובנים.
// כל יוצרת כותבת טקסט חופשי (מיקום / מה היא מצלמת / על עצמה), וכאן הוא מתורגם
// אוטומטית לאזורים ולקטגוריות הקבועים של הסינון.

// ---------- כלי עזר ----------

// נרמול טקסט עברי להשוואה: בלי ניקוד, גרשיים ומקפים, ואחידות כתיב מלא/חסר (וו→ו, יי→י).
export function normalize(text) {
  return ` ${String(text || '')
    .replace(/[֑-ׇ]/g, '')
    .replace(/["'`׳״]/g, '')
    .replace(/[-–—_,./\\|()]/g, ' ')
    .replace(/וו/g, 'ו')
    .replace(/יי/g, 'י')
    .replace(/\s+/g, ' ')
    .trim()} `
}

// מחזיר את כל המפתחות שנמצאו בטקסט. מחפש קודם את הביטויים הארוכים ו"מוחק" אותם,
// כדי ש"אור יהודה" לא ייתפס גם כ"יהודה", ו"בנימינה" לא ייתפס כ"בנימין".
function findAll(text, entries) {
  let rest = normalize(text)
  const found = new Set()
  for (const [re, keys] of entries) {
    re.lastIndex = 0
    if (re.test(rest)) {
      keys.forEach((k) => found.add(k))
      re.lastIndex = 0
      rest = rest.replace(re, ' | ')
    }
  }
  return found
}

// אותיות שימוש שיכולות להופיע לפני מילה ("בירושלים", "והמרכז", "לחתונות", "ובבית שמש").
const PREFIX = '(?:[ובלמשכ]{0,2}ה?)'

const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// בונה רשימת [ביטוי רגולרי, מפתחות] ממוינת מהארוך לקצר.
// wholeWord=true: התאמה למילה שלמה; אחרת רק מתחילת מילה (כדי לתפוס גם רבים ונטיות).
function buildEntries(map, wholeWord) {
  const entries = []
  for (const [key, phrases] of Object.entries(map)) {
    for (const p of phrases) {
      const core = normalize(p).trim()
      const end = wholeWord ? '(?=\\s)' : ''
      entries.push([core.length, new RegExp('\\s' + PREFIX + escapeRegExp(core) + end, 'g'), [key]])
    }
  }
  return entries.sort((a, b) => b[0] - a[0]).map(([, re, keys]) => [re, keys])
}

